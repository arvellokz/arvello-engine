EXPECTED = {}
KIND_NOTE = {
    "tube": "металлические трубы заходят друг в друга в узлах: длины реза в спецификации завышены; нужно правило стыка (какая труба сквозная)",
    "board": "плитные детали перекрываются: деталь посчитана дважды или нужен паз/вырез",
}


def geometry_findings():
    rows = []
    for sku in products():
        s = compile(sku, default_options(sku))
        P = [p for p in s["parts"] if p["kind"] in MADE or p["kind"] == "buy"]
        pairs = []
        for i, a in enumerate(P):
            for b in P[i + 1:]:
                ov = [min(a[k + "1"], b[k + "1"]) - max(a[k + "0"], b[k + "0"]) for k in "xyz"]
                if all(o > 0.5 for o in ov) and not expected_overlap(a, b):
                    pairs.append((a, b, ov))
        if pairs:
            short = sku.replace("ARV-", "")
            if short in EXPECTED:
                continue
            kinds = {a["kind"] for a, b, _ in pairs} | {b["kind"] for a, b, _ in pairs}
            ex = "; ".join(f"{a['id']} × {b['id']} ({round(ov[0])}×{round(ov[1])}×{round(ov[2])})" for a, b, ov in pairs[:3])
            note = KIND_NOTE["tube"] if kinds <= {"tube", "buy"} else KIND_NOTE["board"]
            rows.append((sku, "3D / спецификация", f"Пересечение деталей: {len(pairs)} пар, напр. {ex}", note,
                         "данные" if kinds <= {"tube", "buy", "board"} else "решение", "открыто"))
        top = [p for p in s["parts"] if p["group"] == "top" and p["kind"] == "board"]
        if top:
            main_top = max(top, key=lambda p: (p["x1"] - p["x0"]) * (p["y1"] - p["y0"]))
            zt = main_top["z1"]
            above = [p for p in s["parts"] if p["z1"] > zt + 0.5 and p["kind"] not in ("context",) and p["group"] == "top"
                     and p["id"] != "ledge"]          # стойка ресепшн выше рабочей крышки — так задумано
            for p in above:
                rows.append((sku, "лист 1", f"Деталь {p['id']} выше плоскости крышки на {p['z1'] - zt:g} мм — габарит по высоте завышен",
                             "Утопить лючок/кабель-канал в крышку (вырез) или исключить из габарита", "данные", "открыто"))
    return rows


def main(out: Path):
    out.mkdir(parents=True, exist_ok=True)
    rows = SYSTEMIC + FIXED + geometry_findings()
    head = ["Изделие", "Лист", "Ошибка или недостаток", "Исправление", "Тип", "Статус"]
    with open(out / "registry.csv", "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f); w.writerow(head); w.writerows(rows)
    md = ["# Реестр ошибок чертежей Arvello (29.10.2026)", "",
          "Тип: «данные» — исправляется по исходной геометрии и правилам генератора; «решение» — нужен конструктивный выбор.", "",
          "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    md += ["| " + " | ".join(str(c).replace("|", "/") for c in r) + " |" for r in rows]
    (out / "registry.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    return rows


if __name__ == "__main__":
    r = main(Path(sys.argv[1]))
    print(len(r), "пунктов")
