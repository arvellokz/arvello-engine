def verify(s, report=None, texts=None):
    """Проверки перед передачей (пункт 7 задания). Возвращает [(проверка, ok, подробности)]."""
    d = s["derived"]
    out = []
    add = lambda n, ok, t: out.append((n, bool(ok), t))
    up, low, leg, link = P(s, "F1-UP"), P(s, "F1-LOW"), P(s, "F1-FRONT"), P(s, "LINK-1")
    f1, f2 = P(s, "F1-UP"), P(s, "F2-UP")
    # 1. сборка = детали
    add("Высота рамы = 2 перекладины + стойка", up["z1"] - low["z0"] == 40 + 40 + (leg["z1"] - leg["z0"]),
        f"{up['z1'] - low['z0']:g} = 40 + 40 + {leg['z1'] - leg['z0']:g}")
    add("Высота стола = подпятник + рама + столешница", d["feet_h"] + d["frame_h"] + d["top_t"] == d["height"],
        f"{d['feet_h']} + {d['frame_h']} + {d['top_t']} = {d['height']}")
    add("Связь = просвет между рамами", link["x1"] - link["x0"] == f2["x0"] - f1["x1"] and link["x0"] == f1["x1"],
        f"{link['x1'] - link['x0']:g} = {f2['x0'] - f1['x1']:g}")
    add("Верх рам, связей, пластин — одна плоскость", len({p["z1"] for p in s["parts"] if p["id"].endswith("-UP") or
                                                          p["id"].startswith(("LINK", "PL-"))}) == 1, f"Z = {up['z1']:g}")
    add("Перекладина = рама по ширине", low["y1"] - low["y0"] == d["bar"], f"{d['bar']}")
    # 2. отверстия
    for h in s["holes"]:
        pl = P(s, h["part_id"])
        c = ((pl["x0"] + pl["x1"]) / 2, (pl["y0"] + pl["y1"]) / 2)
        if c != (h["x"], h["y"]):
            add(f"Ось паза {h['id']} = центр пластины", False, f"{c} ≠ {(h['x'], h['y'])}")
    add("Оси пазов пластин = оси отверстий столешницы (8 из 8)", all(
        ((P(s, h["part_id"])["x0"] + P(s, h["part_id"])["x1"]) / 2, (P(s, h["part_id"])["y0"] + P(s, h["part_id"])["y1"]) / 2) == (h["x"], h["y"])
        for h in s["holes"]), "координаты отверстий берутся из пластин того же снимка")
    tube_faces = {p["x0"] for p in s["parts"] if p["id"].endswith("-UP")} | {p["x1"] for p in s["parts"] if p["id"].endswith("-UP")}
    add("От оси паза до грани трубы 25", all(min(abs(h["x"] - t) for t in tube_faces) == 25 for h in s["holes"]), "8 мест")
    # 3. количества
    cnt = lambda pre: len(parts(s, pre))
    hw = {h["id"]: h["qty"] for h in s["hardware"]}
    add("Количества деталей в спецификации", (cnt("F1-LOW") + cnt("F2-LOW"), cnt("F1-UP") + cnt("F2-UP"),
                                              len([p for p in s["parts"] if p["id"].endswith(("FRONT", "BACK"))]),
                                              cnt("LINK"), cnt("PL-"), cnt("CAP")) == (2, 2, 4, 2, 8, 8), "2 / 2 / 4 / 2 / 8 / 8")
    add("Крепёж = числу отверстий", hw["INSERT-M6"] == hw["SCREW-M6x16"] == hw["WASHER-6.4x18"] == len(s["holes"]) == 8,
        f"{hw['INSERT-M6']} втулок, {hw['SCREW-M6x16']} винтов, {hw['WASHER-6.4x18']} шайб")
    add("Подпятники = гайки = контргайки = 4", hw["FOOT-M8"] == hw["RIVNUT-M8"] == hw["NUT-M8"] == cnt("FOOT") == 4, "4")
    # 4. остаток при глухом сверлении
    T = d["top_t"]
    add("Остаток плиты при сверлении ≥ 7 мм", T - (17 + 0.5) >= 7, f"{T} − 17,5 = {T - 17.5:g}")
    add("Втулка 15 короче глубины отверстия 17", 15 < 17, "запас 2 мм на дне")
    add("Винт не упирается в дно втулки", 16 - 4 - 1.6 <= 15, "вход 10,4 из 15")
    # 5. доступ инструмента: под каждой осью паза свободный столб Ø18 до пола
    blocked = []
    for h in s["holes"]:
        for p in s["parts"]:
            if p["kind"] in ("context", "buy_part") or p["id"] == h["part_id"] or p["z1"] > 721:
                continue
            if p["x0"] < h["x"] + 9 and p["x1"] > h["x"] - 9 and p["y0"] < h["y"] + 9 and p["y1"] > h["y"] - 9:
                blocked.append((h["id"], p["id"]))
    add("Доступ ключа снизу к каждому винту", not blocked, "свободно" if not blocked else str(blocked))
    fy = (parts(s, "FOOT-1")[0]["y0"] + parts(s, "FOOT-1")[0]["y1"]) / 2 - low["y0"]
    add("Гайка M8 не мешает заглушке (ось ≥ 13 от торца)", fy >= 13, f"ось {fy:g} от торца; заглушка 2; гайка Ø≈11 — уточнить В-6")
    # 6. пересечения деталей (кроме заглушек внутри трубы)
    clash = []
    M = [p for p in s["parts"] if p["kind"] in ("tube", "plate", "board")]
    for i, a in enumerate(M):
        for b in M[i + 1:]:
            if all(min(a[k + "1"], b[k + "1"]) - max(a[k + "0"], b[k + "0"]) > 0.01 for k in "xyz"):
                clash.append((a["id"], b["id"]))
    add("Детали не пересекаются", not clash, "нет" if not clash else str(clash[:4]))
    # 7–8. листы
    if report is not None:
        bad = {k: v for k, v in report.items() if v}
        add("Наложения текста и выход за рамку", not bad, "нет" if not bad else str(bad))
    if texts is not None:
        import re
        refs = {int(x) for t in texts for x in re.findall(r"л(?:ист)?\.?\s0?(\d)\b", t)}
        qs = {q[0] for q in QUESTIONS}
        qrefs = {x for t in texts for x in re.findall(r"В-\d+", t)}
        add("Все ссылки на листы существуют", refs <= set(range(1, TOTAL + 1)), f"ссылки: {sorted(refs)}")
        add("Все упомянутые вопросы В-n есть на листе 09", qrefs <= qs, f"упомянуто {len(qrefs)}, на листе {len(qs)}")
    return out


