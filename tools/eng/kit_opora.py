def _tube(sh, x, y, L, sc, title, note, holes=(), bottom_holes=True):
    """Труба 40×40×2 — вид сбоку в масштабе 1:sc; внутренние стенки — невидимые линии."""
    w, h = L / sc, 40 / sc
    sh.rect(x, y, x + w, y + h, VIS)
    sh.line(x, y + 2 / sc, x + w, y + 2 / sc, HID); sh.line(x, y + h - 2 / sc, x + w, y + h - 2 / sc, HID)
    sh.dim_h(x, x + w, y + h, y + h, y + h + 6, f"{L:g}")
    for hx in holes:
        cx = x + hx / sc
        sh.line(cx, y - 2.5, cx, y + h + 2.5, CTR)
    if holes:
        sh.dim_h(x, x + holes[0] / sc, y, y, y - 5, f"{holes[0]:g}")
    sh.text(x, y + h + 14, title, size=7.4, weight="bold")
    sh.text(x, y - (11 if holes else 3), note, size=6.2, va="top")


