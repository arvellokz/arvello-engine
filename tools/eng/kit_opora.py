def sheet_base(s, stamp):
    sc = scale_for(s)
    sh = Sheet("Подстолье — сварная сборочная единица, поз. 2", stamp, 3, TOTAL, f"1:{sc}")
    met = [p for p in s["parts"] if p["kind"] in ("tube", "plate", "cap")]
    bx0 = min(p["x0"] for p in met); bx1 = max(p["x1"] for p in met)
    by0 = min(p["y0"] for p in met); by1 = max(p["y1"] for p in met)
    bz0 = min(p["z0"] for p in met); bz1 = max(p["z1"] for p in met)
    f1, f2 = P(s, "F1-UP"), P(s, "F2-UP")
    low, up, leg, link = P(s, "F1-LOW"), P(s, "F1-UP"), P(s, "F1-FRONT"), P(s, "LINK-1")
    is_met = lambda p: p["kind"] in ("tube", "plate")
    # ---- вид спереди
    vf = View(sh, sc, (50, 185), m0=(bx0, bz0))
    _draw(vf, s, "front", only=is_met)
    xl, yb = vf.p(bx0, bz0); xr, yt = vf.p(bx1, bz1)
    sh.dim_h(xl, xr, yt, yt, yt + 10, f"{bx1 - bx0:g}")
    ia, ib = vf.p(f1["x1"], 0)[0], vf.p(f2["x0"], 0)[0]
    sh.dim_h(ia, ib, yt - 4, yt - 4, yt - 11, f"{f2['x0'] - f1['x1']:g}")
    sh.dim_h(vf.p(f1["x0"], 0)[0], vf.p(f2["x1"], 0)[0], yb, yb, yb - 8, f"{f2['x1'] - f1['x0']:g}")
    sh.dim_v(yb, yt, xr, xr, xr + 9, f"{bz1 - bz0:g}")
    sh.text(xl, yb - 22, "Вид спереди (подпятники не показаны)", size=8, weight="bold")
