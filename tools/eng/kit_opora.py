def _draw(view, s, proj, skip=("context", "buy_part", "cap"), order=None, top_fill=True, only=None):
    """Проекция деталей снимка: proj — 'front' (x,z), 'side' (y,z), 'plan' (x,y)."""
    key = {"front": lambda p: -p["y0"], "side": lambda p: p["x1"], "plan": lambda p: p["z1"]}[proj]
    for p in sorted(s["parts"], key=order or key):
        if p["kind"] in skip or (only and not only(p)):
            continue
        u0, v0, u1, v1 = {"front": ("x0", "z0", "x1", "z1"), "side": ("y0", "z0", "y1", "z1"),
                          "plan": ("x0", "y0", "x1", "y1")}[proj]
        view.rect(p[u0], p[v0], p[u1], p[v1], HID if p["kind"] == "buy" else VIS,
                  fill=("#E9ECEF" if (p["id"] == "TOP" and top_fill) else "white"))


