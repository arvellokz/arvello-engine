    for (x, z, lab, ox, oy) in ((f1["x1"], up["z0"], "Ш1", 2.5, -6), (f2["x0"], low["z1"], "Ш1", -7, 3),
                                 (f1["x1"], (link["z0"] + link["z1"]) / 2, "Ш2", 2.5, 2.5)):
        px, pz = vf.p(x, z)
        sh.circle(px, pz, 1.5, st=THIN)
        sh.text(px + ox, pz + oy, lab, size=6.2)
    # ---- вид справа (рама F2)
    vs = View(sh, sc, (225, 185), m0=(by0, bz0))
