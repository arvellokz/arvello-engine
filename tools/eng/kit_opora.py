def scale_for(s):
    """Стандартный масштаб видов изделия: 1:10 до длины 1700, дальше 1:15 (ГОСТ 2.302)."""
    return 10 if s["derived"]["length"] <= 1700 else 15


def P(s, pid):
    return next(p for p in s["parts"] if p["id"] == pid)


def parts(s, prefix):
    return [p for p in s["parts"] if p["id"].startswith(prefix)]


